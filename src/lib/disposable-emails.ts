/**
 * Checks whether an email address belongs to a known temporary, disposable, or burner domain.
 * Supports subdomain extraction (e.g., `user@xyz.mailinator.com` -> `mailinator.com`).
 */
export function isDisposableEmail(email: string): boolean {
  if (!email || typeof email !== "string" || !email.includes("@")) {
    return false;
  }

  const normalized = email.toLowerCase().trim();
  const parts = normalized.split("@");
  if (parts.length !== 2) return false;

  const domain = parts[1].trim();

  // 1. Direct match
  if (DISPOSABLE_DOMAIN_SET.has(domain)) {
    return true;
  }

  // 2. Subdomain check (e.g. `sub.tempmail.com` -> `tempmail.com`)
  const domainParts = domain.split(".");
  if (domainParts.length > 2) {
    const parentDomain = domainParts.slice(-2).join(".");
    if (DISPOSABLE_DOMAIN_SET.has(parentDomain)) {
      return true;
    }
  }

  // 3. Common pattern match for dynamically generated disposable subdomains
  if (
    domain.includes("mailinator") ||
    domain.includes("guerrillamail") ||
    domain.includes("tempmail") ||
    domain.includes("10minutemail") ||
    domain.includes("throwaway") ||
    domain.includes("fakeinbox") ||
    domain.includes("trashmail") ||
    domain.includes("burnermail") ||
    domain.includes("sharklasers")
  ) {
    return true;
  }

  return false;
}
